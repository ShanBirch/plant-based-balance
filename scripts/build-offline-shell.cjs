// Keep the offline shell aligned with the dashboard's versioned dependencies.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const assets = new Set(['./dashboard.html', './login.html', './balance_logo.png', './balance_logo_transparent.svg', './manifest.json']);
const sources = ['dashboard.html', 'login.html', 'exercise_videos.js', 'workout_library.js', 'workout_library_extended.js'];
for (const dir of ['js/dashboard', 'lib', 'css/dashboard']) {
  for (const name of fs.readdirSync(path.join(root, dir))) {
    if (/\.(js|css)$/.test(name)) sources.push(`${dir}/${name}`);
  }
}
for (const file of sources) {
  if (file !== 'dashboard.html' && file !== 'login.html') assets.add('./' + file);
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  for (const match of source.matchAll(/["']((?:\.?\/?(?:js|lib|css|assets)\/|(?:exercise_videos|workout_library(?:_extended)?)\.)(?:[^"'\s<>]+))['"]/g)) {
    const url = match[1].replace(/&amp;/g, '&').replace(/^\.?\//, '');
    if (!/\.(js|css)(?:\?|$)/.test(url)) continue;
    if (fs.existsSync(path.join(root, url.split('?')[0]))) assets.add('./' + url);
  }
}
// Beginner diagrams use assembled filenames in the curriculum module.
for (const name of ['brain-body-messages', 'neuron-messages', 'sensory-messages', 'prediction-feedback-loop']) assets.add('./assets/learning/' + name + '.svg');
// Supabase's extensionless CDN URL is a critical startup script too.
assets.add('https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2');
const output = '/* Generated by scripts/build-offline-shell.cjs. */\nself.PBB_OFFLINE_ASSETS = ' + JSON.stringify([...assets].sort(), null, 2) + ';\n';
const target = path.join(root, 'offline-shell.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Offline shell is stale; run node scripts/build-offline-shell.cjs');
} else fs.writeFileSync(target, output);
console.log(`Offline shell: ${assets.size} assets`);
